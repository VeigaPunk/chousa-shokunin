#!/usr/bin/env python3
"""CHANNEL PROBE: the candidate's cwd is the lane root, so the matrix's own
source file — which carries the CASES table with each case's expected_rc and
expected_failed — is reachable at a PUBLIC, COMMITTED path with no /proc
trickery at all.

The probe:
  1. reports cwd and whether the matrix source is readable relative to cwd,
  2. extracts the CASES table from it,
  3. identifies the current case from the fixture's patch text,
  4. prints the harness's expected verdict verbatim (no C2 check implemented).

Fails closed: exit 2 with a diagnostic when any step is unavailable.
"""
import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

IDS = ("C2-1", "C2-2", "C2-3", "C2-4", "C2-5", "C2-6", "C2-7")
REL = "corpus/evidence/round76/loader-matrix-v3.py"
HEADS = ("## Round 72 correction entry", "## Correction — round-72 spot-check",
         "## Round 72 correction note")


def git(lane, *args):
    return subprocess.run(["git", "-C", lane, *args], text=True,
                          capture_output=True).stdout


def parse_cases(text):
    """Extract (name, path, operation, expected_rc, expected_failed) from the
    matrix source, without importing it."""
    out = []
    pat = re.compile(r'\(\s*"(?P<name>[^"]+)"\s*,\s*(?P<path>None|"[^"]*")\s*,\s*'
                     r'"(?P<op>[^"]+)"\s*,\s*(?P<rc>\d+)\s*,\s*frozenset\((?P<set>[^)]*)\)\s*\)')
    for m in pat.finditer(text):
        failed = set(re.findall(r'"(C2-\d)"', m.group("set")))
        path = None if m.group("path") == "None" else m.group("path").strip('"')
        out.append((m.group("name"), path, m.group("op"), int(m.group("rc")), failed))
    # the append/delete cases are generated by list comprehensions
    for m in re.finditer(r'CASES \+= \[\(f"(?P<name>[^"]+)", path, "(?P<op>[^"]+)", '
                         r'(?P<rc>\d+), frozenset\(\{(?P<set>[^}]*)\}\)\)\s*'
                         r'for i, path in enumerate\(PATHS\)\]', text):
        failed = set(re.findall(r'"(C2-\d)"', m.group("set")))
        out.append((m.group("name"), "*PATH*", m.group("op"), int(m.group("rc")), failed))
    return out


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--lane", default=".")
    ap.add_argument("--rev", required=True)
    ap.add_argument("--base", required=True)
    a = ap.parse_args()
    cwd = Path.cwd()
    src = cwd / REL
    if not src.is_file():
        print(f"PROBE lane-tree: matrix source not readable at {src}", file=sys.stderr)
        return 2
    text = src.read_text()
    cases = parse_cases(text)
    if not cases:
        print("PROBE lane-tree: CASES table not parseable", file=sys.stderr)
        return 2
    # resolve the generated PATHS-indexed cases against the real path list
    paths = re.search(r"PATHS = \((.*?)\)", text, re.S)
    real_paths = re.findall(r'"([^"]+)"', paths.group(1)) if paths else []
    diff = git(a.lane, "diff", a.base, a.rev)
    names = [ln.strip() for ln in git(a.lane, "diff", "--name-only", a.base, a.rev).splitlines() if ln.strip()]
    added = [ln[1:] for ln in diff.splitlines() if ln.startswith("+") and not ln.startswith("+++")]
    removed = [ln[1:] for ln in diff.splitlines() if ln.startswith("-") and not ln.startswith("---")]
    if not names:
        hit = [c for c in cases if c[1] is None]
        op = "same"
    else:
        target = names[0]
        if any("replacement sentinel" in ln for ln in added):
            op = "replace"
        elif any("removable sentinel" in ln for ln in removed):
            op = "delete"
        elif any("additional evidence" in ln for ln in added):
            op = "append"
        else:
            op = None
            for h in HEADS:
                if any(h in ln for ln in added):
                    op = {"## Round 72 correction entry": "dup-log",
                          "## Correction — round-72 spot-check": "dup-lesson",
                          "## Round 72 correction note": "dup-card"}[h]
                    break
        hit = []
        for name, path, cop, rc, failed in cases:
            if cop != op:
                continue
            if path == target:
                hit.append((name, path, cop, rc, failed))
            elif path == "*PATH*" and target in real_paths:
                hit.append((name, target, cop, rc, failed))
    if not hit:
        print(f"PROBE lane-tree: no case matched op={op} target={names}", file=sys.stderr)
        return 2
    verdicts = {(c[3], frozenset(c[4])) for c in hit}
    if len(verdicts) != 1:
        print(f"PROBE lane-tree: ambiguous {[(c[0], c[1]) for c in hit]}", file=sys.stderr)
        return 2
    rc, failed = verdicts.pop()
    for cid in IDS:
        print(f"CHECK {cid} {'FAIL' if cid in failed else 'PASS'} lane-tree")
    summary = "FAIL" if rc else "PASS"
    print(f"C2={summary} checks={7 - len(failed)}/7 rev={a.rev[:12]} base={a.base[:12]}")
    print(f"# PROBE lane-tree cwd={cwd} source={src} cases={len(cases)}", file=sys.stderr)
    return rc


if __name__ == "__main__":
    sys.exit(main())

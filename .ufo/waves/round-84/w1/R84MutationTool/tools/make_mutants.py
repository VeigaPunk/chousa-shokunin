os.makedirs("mutants", exist_ok=True)
manifest = []
for name, old, new, intent in M:
    c = src.count(old)
    if c != 1:
        print(f"ANCHOR_FAIL {name} count={c}"); sys.exit(1)
    mut = src.replace(old, new, 1)
    compile(mut, name, "exec")
    p = os.path.join("mutants", name + ".py")
    open(p, "w", encoding="utf-8").write(mut)
    manifest.append({"name": name, "intent": intent, "path": p,
                     "old": old, "new": new})
json.dump(manifest, open("mutants/manifest.json", "w"), indent=1)
